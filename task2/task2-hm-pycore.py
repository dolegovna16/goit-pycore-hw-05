import re
from typing import Callable


def generator_numbers(text: str):
    """Знаходить у тексті дійсні числа та віддає їх по одному.

    Числа мають бути записані без помилок і відокремлені
    пробілами з обох боків.

    Args:
        text: рядок, у якому шукаємо числа.

    Yields:
        float: наступне знайдене число.
    """
    # Шаблон: пробіл, потім число виду 123.45, потім пробіл.
    # Пробіли по краях беруть лише числа, відокремлені пробілами.
    # Дужки утворюють групу, тож findall поверне число без пробілів.
    pattern = r" (\d+\.\d+) "
    for number in re.findall(pattern, text):
        # re повертає рядки, тому перетворюємо їх на float
        yield float(number)


def sum_profit(text: str, func: Callable):
    """Обчислює загальну суму чисел у тексті.

    Args:
        text: рядок із числами.
        func: функція-генератор, що віддає числа з тексту.

    Returns:
        float: сума всіх знайдених чисел.
    """
    # Отримуємо генератор чисел із тексту
    numbers = func(text)
    # sum() послідовно бере значення з генератора та додає їх
    summary = sum(numbers)
    return summary


# Приклад використання
text = "Загальний дохід працівника складається з декількох частин: " \
       "1000.01 як основний дохід, доповнений додатковими надходженнями " \
       "27.45 і 324.00 доларів."
total_income = sum_profit(text, generator_numbers)
print(f"Загальний дохід: {total_income}")  # Загальний дохід: 1351.46